"""Schema and repository-hygiene checks for the public release."""

from __future__ import annotations

import csv
import re
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "synthetic_cohort.csv"
DICTIONARY = ROOT / "data_dictionary.csv"


class DataSchemaTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with DICTIONARY.open(newline="", encoding="utf-8") as handle:
            cls.fields = [row["field"] for row in csv.DictReader(handle)]
        with DATA.open(newline="", encoding="utf-8") as handle:
            cls.rows = list(csv.DictReader(handle))

    def test_dictionary_covers_every_column(self):
        self.assertEqual(set(self.rows[0].keys()), set(self.fields))

    def test_all_rows_have_required_values(self):
        for row in self.rows:
            for field in self.fields:
                self.assertTrue(row[field].strip(), f"empty {field} in {row}")

    def test_splits_and_class_balance(self):
        self.assertEqual(len(self.rows), 180)
        for split in ("train", "internal_test", "external_test"):
            subset = [r for r in self.rows if r["split"] == split]
            self.assertGreater(len(subset), 30, split)
            self.assertEqual({r["Group"] for r in subset}, {"0", "1"}, split)

    def test_ids_are_synthetic_and_unique(self):
        ids = [r["sample_id"] for r in self.rows]
        self.assertEqual(len(ids), len(set(ids)))
        for sid in ids:
            self.assertRegex(sid, r"^SYN-(T|V|E)-\d{3}$")
            self.assertNotIn("GSE", sid)
            self.assertNotIn("GSM", sid)

    def test_allowed_categories(self):
        for row in self.rows:
            self.assertIn(row["PAS_Macrophages"], {"0", "1", "2"})
            self.assertIn(row["Group"], {"0", "1"})


class RepositoryHygieneTest(unittest.TestCase):
    FORBIDDEN_NAMES = {
        "train_data.csv",
        "test_data.csv",
        "external_test_data.csv",
        "code.R",
    }
    FORBIDDEN_SUFFIXES = {
        ".svs",
        ".ndpi",
        ".scn",
        ".czi",
        ".nd2",
        ".lif",
        ".mrxs",
        ".tif",
        ".tiff",
        ".dcm",
        ".docx",
        ".pdf",
    }
    TEXT_SUFFIXES = {".md", ".csv", ".py", ".R", ".r", ".ijm", ".yml", ".yaml", ".json", ".cff", ".txt"}

    def test_no_manuscript_or_results_tracked(self):
        if not (ROOT / ".git").exists():
            self.skipTest("not a Git checkout")
        tracked = subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True).splitlines()
        bad = [f for f in tracked if f.startswith(("manuscript/", "results/"))]
        self.assertEqual(bad, [], f"private manuscript/results are tracked: {bad}")

    def test_no_study_data_files(self):
        found = [p for p in ROOT.rglob("*") if p.name in self.FORBIDDEN_NAMES]
        self.assertEqual(found, [], f"forbidden study files present: {found}")

    def test_no_image_or_document_attachments(self):
        allowed = ROOT / "results" / "figures"
        found = [
            p for p in ROOT.rglob("*")
            if p.is_file()
            and p.suffix.lower() in self.FORBIDDEN_SUFFIXES
            and allowed not in p.parents
        ]
        # Figures generated by 08_figures.R are synthetic and live under results/figures/.
        # Any pathology image or document outside that generated-output directory is a
        # release blocker.
        self.assertEqual(found, [], f"image/document files present: {found}")

    def test_no_large_files(self):
        for path in ROOT.rglob("*"):
            if path.is_file() and ".git" not in path.parts:
                self.assertLess(path.stat().st_size, 2_000_000, f"large file: {path}")

    def test_no_study_accession_strings(self):
        pattern = re.compile(r"GSE\d{4,}|GSM\d{4,}")
        for path in ROOT.rglob("*"):
            if path.is_file() and path.suffix.lower() in self.TEXT_SUFFIXES:
                text = path.read_text(encoding="utf-8", errors="ignore")
                self.assertIsNone(pattern.search(text), f"study accession in {path}")


if __name__ == "__main__":
    unittest.main()
